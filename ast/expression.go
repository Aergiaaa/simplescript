package ast

import (
	"bytes"
	"strings"

	"github.com/Aergiaaa/simplescript/token"
)

type Expression interface {
	Node
	expressionNode()
}

type AssignmentExpression struct {
	Token token.Token // `=`
	Name  *Identifier
	Val   Expression
}

func (ae *AssignmentExpression) expressionNode()      {}
func (ae *AssignmentExpression) TokenLiteral() string { return ae.Token.Literal }
func (ae *AssignmentExpression) String() string {
	var out bytes.Buffer
	out.WriteString(ae.Name.String())
	out.WriteString(" = ")
	if ae.Val != nil {
		out.WriteString(ae.Val.String())
	}

	return out.String()
}

type ForExpression struct {
	Token     token.Token // `for`
	Condition Expression
	Body      *BlockStatement
}

func (fe *ForExpression) expressionNode()      {}
func (fe *ForExpression) TokenLiteral() string { return fe.Token.Literal }
func (fe *ForExpression) String() string {
	var out bytes.Buffer

	out.WriteString("for")
	if fe.Condition != nil {
		out.WriteString(fe.Condition.String())
	}
	out.WriteString(" ")
	out.WriteString(fe.Body.String())

	return out.String()
}

type IfExpression struct {
	Token       token.Token
	Condition   Expression
	Consequence *BlockStatement
	Alternative *BlockStatement
}

func (ie *IfExpression) expressionNode()      {}
func (ie *IfExpression) TokenLiteral() string { return ie.Token.Literal }
func (ie *IfExpression) String() string {
	var out bytes.Buffer

	out.WriteString("if")
	out.WriteString(ie.Condition.String())
	out.WriteString(" ")
	out.WriteString(ie.Consequence.String())

	if ie.Alternative != nil {
		out.WriteString("else ")
		out.WriteString(ie.Alternative.String())
	}

	return out.String()
}

type CallExpression struct {
	Token token.Token // should be '(' because at i.e add(1,2), the 'add' identifier already consumed
	Func  Expression  // Identifier or Func Literal
	Args  []Expression
}

func (ce *CallExpression) expressionNode()      {}
func (ce *CallExpression) TokenLiteral() string { return ce.Token.Literal }
func (ce *CallExpression) String() string {
	var out bytes.Buffer

	var args []string
	for _, a := range ce.Args {
		args = append(args, a.String())
	}

	out.WriteString(ce.Func.String())
	out.WriteString("(")
	out.WriteString(strings.Join(args, ", "))
	out.WriteString(")")

	return out.String()
}

